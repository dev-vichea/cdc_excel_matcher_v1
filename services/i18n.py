import base64
from pathlib import Path

_ASSETS_DIR = Path(__file__).parent / "assets"
_CACHED_FONT_CSS = None


def get_font_css() -> str:
    """Return @font-face rules with embedded WOFF for Regular (400) and SemiBold (600)."""
    global _CACHED_FONT_CSS
    if _CACHED_FONT_CSS is not None:
        return _CACHED_FONT_CSS

    reg_woff = _ASSETS_DIR / "KantumruyPro.woff"
    sb_woff = _ASSETS_DIR / "KantumruyPro-SemiBold.woff"

    reg_b64 = base64.b64encode(reg_woff.read_bytes()).decode("utf-8") if reg_woff.exists() else ""
    sb_b64 = base64.b64encode(sb_woff.read_bytes()).decode("utf-8") if sb_woff.exists() else ""

    rules = []
    if reg_b64:
        rules.append(f"""
@font-face {{
  font-family: 'Kantumruy Pro';
  font-style: normal;
  font-weight: 400;
  font-display: swap;
  src: url('data:font/woff;base64,{reg_b64}') format('woff'),
       url('https://fonts.gstatic.com/s/kantumruypro/v12/1q2TY5aECkp34vEBSPFOmJxwvk_pilU8OGNfyg1urEs0.ttf') format('truetype');
}}
""")
    if sb_b64:
        rules.append(f"""
@font-face {{
  font-family: 'Kantumruy Pro';
  font-style: normal;
  font-weight: 600;
  font-display: swap;
  src: url('data:font/woff;base64,{sb_b64}') format('woff'),
       url('https://fonts.gstatic.com/s/kantumruypro/v12/1q2TY5aECkp34vEBSPFOmJxwvk_pilU8OGNfyg2wq0s0.ttf') format('truetype');
}}
@font-face {{
  font-family: 'Kantumruy Pro';
  font-style: normal;
  font-weight: 700;
  font-display: swap;
  src: url('data:font/woff;base64,{sb_b64}') format('woff'),
       url('https://fonts.gstatic.com/s/kantumruypro/v12/1q2TY5aECkp34vEBSPFOmJxwvk_pilU8OGNfyg2wq0s0.ttf') format('truetype');
}}
""")

    if not rules:
        rules.append("@import url('https://fonts.googleapis.com/css2?family=Kantumruy+Pro:wght@400;600&display=swap');")

    _CACHED_FONT_CSS = "\n".join(rules)
    return _CACHED_FONT_CSS


